/** WhaleLogo 属性。 */
export interface WhaleLogoProps {
  /** 外框边长（px）。默认 34。 */
  readonly size?: number
  /** 额外类名（调用方定位用）。 */
  readonly className?: string
  /**
   * 是否播放动效。默认 true；面板在「正在加载」等场景传 false 时只保留静态图形
   * （不是删掉动画类，而是换成不带动画的类，避免残留的 animation 属性）。
   */
  readonly animated?: boolean
}

/**
 * 会动的 DSH 鲸鱼。
 *
 * 结构上分三层，各自承担一组动效，互不干扰：
 *   body  → 呼吸缩放（整只一起）
 *   shape → 本体填充（currentColor）
 *   sweep → 沿轮廓跑的流光描边（主色）
 * 摆尾由外层 span 的 hover 触发（hover 在 svg 内部子元素上不好控），
 * 所以 hover 判定放在 span 上、旋转作用在 body 上。
 */
export function WhaleLogo({ size = 34, className, animated = true }: WhaleLogoProps): JSX.Element {
  const classes = [
    css.whale,
    animated ? '' : css.whaleStill,
    className ?? '',
  ].filter(item => item !== '').join(' ')

  return (
    <span
      className={classes}
      style={{ width: `${String(size)}px`, height: `${String(size)}px` }}
      data-soul-whale={animated ? 'animated' : 'static'}
    >
      <svg viewBox="0 0 23.16 17.04" width="100%" height="100%" fill="none" aria-hidden="true" focusable="false">
        {/* 底部呼吸光晕：与缩放反相，形成「吸气变亮、呼气变暗」的节奏 */}
        <ellipse className={css.whaleGlow} cx="11.5" cy="15.6" rx="6.4" ry="0.9" fill="currentColor" />
        <g className={css.whaleBody}>
          {/* 本体：填充色吃 currentColor，主题切换自动跟随 */}
          <path className={css.whaleShape} d={FISH_LOGO_PATH} fill="currentColor" />
          {/* 流光：同一条 path 描边，dasharray 只留一小段，靠 dashoffset 循环跑 */}
          <path
            className={css.whaleSweep}
            d={FISH_LOGO_PATH}
            fill="none"
            stroke="currentColor"
            strokeWidth="0.62"
            strokeLinecap="round"
            strokeLinejoin="round"
          />
        </g>
      </svg>
    </span>
  )
}
