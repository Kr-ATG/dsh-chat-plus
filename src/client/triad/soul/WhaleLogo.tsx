/**
 * dsh-soul — DSH 鲸鱼 logo（那枚会动的）。
 *
 * ── 为什么单独一个文件 ────────────────────────────────────────────────
 * 面板顶部那枚鲸鱼是这次「灵魂卡片化」的门面。用户原话是「灵魂上面是 1 个 DSH 的
 * 黑色鲸鱼的这个图标会动」——它不是装饰性图标，而是这一层的人格化身，所以单独抽
 * 出来做三件事：呼吸、流光、摆尾。
 *
 * ── 设计取舍 ──────────────────────────────────────────────────────────
 * 1. **path 逐字复制，不 import host**。官方 FishLogo 的 path 已在本仓库
 *    src/shot/card.ts 里（FISH_LOGO_PATH，viewBox 0 0 23.16 17.04）。host 与
 *    client 是两个独立产物（一个 ESM/Node、一个 CJS/浏览器），client 半身去 import
 *    host 文件会把整条截图渲染链（markdown-it / shiki / 无头浏览器）拖进浏览器包。
 *    品牌图形是**数据**不是逻辑，复制一份在这里是唯一合理的选择。
 * 2. **零依赖动效**。呼吸（3.6s 缩放）、流光（描边 dashoffset 沿轮廓跑一圈）、
 *    摆尾（hover 时整只鲸鱼绕身体中心轻摆）全部是 CSS animation：没有动画库、
 *    没有 requestAnimationFrame 循环。用户偏好动效，插件又有零运行时依赖的硬约束，
 *    两者在这里不冲突。
 * 3. **颜色走 currentColor**。鲸鱼本体吃父级 color（面板里是 --s-text，亮色主题下
 *    就是那枚「黑色鲸鱼」，暗色主题自动反白）；流光吃 --s-whale-sweep（官方
 *    business-primary token），不另立调色板。
 * 4. **reduced-motion 一票否决**。三组动画在 prefers-reduced-motion 下全部关掉，
 *    静态仍是一枚完整可辨识的鲸鱼（只是不动），不会退化成半个图形。
 * 5. **size 只控外框**。SVG 用 viewBox 自适应缩放，组件只给宽高；不按 size 改
 *    stroke 宽度，否则小尺寸下流光会糊成一团。
 */

